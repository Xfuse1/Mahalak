// الفهرس ثابت لكنه ليس مجانيًّا (آلاف الأشكال)، فيُبنى كسولًا عند أول بحث لا عند تحميل الوحدة،
// ويُحفَظ على مستوى الوحدة كي لا يُعاد بناؤه لكل منتج في قائمة فيها 1500 صنف.
let cachedLookup: Map<string, Set<string>> | null = null

// أطول مفتاح بالكلمات — يحدّد نافذة الـ n-gram في aliasTextFor. يُحسب أثناء البناء لا يدويًّا
// كي لا ينكسر البحث بصمت حين يضيف أحدهم مفتاحًا من ثلاث كلمات.
let maxPhraseWords = 1

// أي محرف خارج الحروف العربية/اللاتينية والأرقام يُعامل فاصلًا: أسماء الكاشير مليئة بـ «-» و«/» و«.»
// («PANADOL-EXTRA/24»)، ولو لم تُقسَّم لضاع المفتاح كلّه.
const SEPARATORS = /[^0-9a-z\u0600-\u06ff]+/

/** يحوّل أي نص إلى عبارة مطبَّعة بكلمات مفصولة بمسافة واحدة — نفس الصيغة المخزَّنة في الفهرس. */
function toPhrase(input: string): string {
  return normalizeArabic(input).split(SEPARATORS).filter(Boolean).join(" ")
}

/**
 * يبني فهرسًا ثنائي الاتجاه: كل شكل مطبَّع يشير إلى مجموعة كل الأشكال المكافئة له (ومنها نفسه).
 * التماثل مضمون بالبناء: `أ` في مجموعة `ب` ⟺ وُجدا معًا في مدخلة واحدة، فلا حاجة لكتابة العكس.
 * يُبنى مرّة واحدة ويُعاد نفس المرجع في كل استدعاء لاحق.
 */
export function buildAliasLookup(): Map<string, Set<string>> {
  if (cachedLookup) return cachedLookup

  const lookup = new Map<string, Set<string>>()

  // المفتاح ليس أعلى مرتبة من قيمه — يدخل المجموعة كأي شكل آخر، وإلا صار البحث أحادي الاتجاه.
  const groups: string[][] = [...Object.entries(BRAND_ALIASES), ...Object.entries(UNIT_SYNONYMS)].map(
    ([key, values]) => [key, ...values],
  )

  for (const group of groups) {
    const forms: string[] = []
    for (const raw of group) {
      const phrase = toPhrase(raw)
      if (phrase && !forms.includes(phrase)) forms.push(phrase)
    }

    for (const form of forms) {
      let set = lookup.get(form)
      if (!set) {
        set = new Set<string>()
        lookup.set(form, set)
      }
      // شكل مشترك بين مدخلتين يجمع المجموعتين معًا (مثل «باراسيتامول» بين بنادول وسيتال) — مقصود.
      for (const other of forms) set.add(other)

      const words = form.split(" ").length
      if (words > maxPhraseWords) maxPhraseWords = words
    }
  }

  cachedLookup = lookup
  return lookup
}

/**
 * الأشكال المكافئة لكلمة واحدة مطبَّعة، بلا الكلمة نفسها. هذه هي الصيغة التي يستهلكها محرّك
 * البحث في خيار `expand`: العميل يكتب «ادول» فتُضاف إليها `adol` قبل أي مطابقة تقريبية.
 */
export function aliasesForToken(token: string): string[] {
  const forms = buildAliasLookup().get(token)
  if (!forms) return []
  const out: string[] = []
  for (const form of forms) if (form !== token) out.push(form)
  return out
}

/**
 * يستخرج من نصّ (اسم منتج غالبًا) ما يطابق الجدول ويُرجع كل الأشكال المكافئة مفصولة بمسافات،
 * لتُدمج كحقل بحث إضافي على المنتج. نصّ لا يطابق شيئًا ⇒ سلسلة فارغة (فلا تُخزَّن حقول فارغة بلا داعٍ).
 */
export function aliasTextFor(text: string): string {
  const words = toPhrase(text).split(" ").filter(Boolean)
  if (words.length === 0) return ""

  const lookup = buildAliasLookup()
  const matched = new Set<string>()

  for (let i = 0; i < words.length; i++) {
    // الأطول أولًا: «كوكا كولا» يجب أن تُلتقط كوحدة قبل أن تُلتقط «كولا» وحدها.
    const window = Math.min(maxPhraseWords, words.length - i)
    for (let size = window; size >= 1; size--) {
      const forms = lookup.get(words.slice(i, i + size).join(" "))
      if (forms) {
        for (const form of forms) matched.add(form)
        break
      }
    }
  }

  return Array.from(matched).join(" ")
}
