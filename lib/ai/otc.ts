/**
 * خطّ الأنابيب الوحيد للنص في هذا الملف. **يجب أن يمرّ عليه الطرفان**: أشكال القائمة وأسماء المنتجات.
 *
 * وحدتهما شرط صحّة لا ترتيب: جدول المرادفات يخزّن أشكاله بتطبيع لا يجرّد أداة التعريف، بينما اسم
 * المنتج يُقسَّم هنا بـ`searchTokens` التي تجرّدها. فكان الشكل المخزَّن «شرايط قياس السكر» لا يطابق
 * أبدًا الاسم المقسَّم «شرايط قياس سكر». وأثر ذلك في **قائمة النقض** أخطر منه في قائمة الإذن:
 * شكلٌ ممنوع لا يُطابَق يعني صنفًا ممنوعًا يمرّ.
 */
function canonical(text: string): string {
  return searchTokens(text).join(" ")
}

function formsOf(groups: readonly string[]): Set<string> {
  const lookup = buildAliasLookup()
  const out = new Set<string>()
  for (const key of groups) {
    const normalized = canonical(key)
    // المجموعة كاملة من الفهرس ثنائي الاتجاه، وإلا كان المفتاح وحده يحمي من تهجئة واحدة فقط.
    // البحث بالمفتاح الخام أيضًا لأن مفاتيح الجدول مخزَّنة بتطبيعه هو لا بتطبيعنا.
    const groupForms = lookup.get(key) ?? lookup.get(normalized)
    if (groupForms) for (const form of groupForms) out.add(canonical(form))
    // المفتاح نفسه يدخل دائمًا ولو لم يكن في الجدول — كي تعمل القائمة على مفاتيح مستقبلية.
    if (normalized) out.add(normalized)
  }
  out.delete("")
  return out
}

// الفهرسان ثقيلان نسبيًّا (آلاف الأشكال) لكنهما ثابتان، فيُبنيان كسولًا مرّة واحدة على مستوى الوحدة.
let allowedForms: Set<string> | null = null
let forbiddenForms: Set<string> | null = null

function allowed(): Set<string> {
  if (!allowedForms) allowedForms = formsOf(OTC_GROUPS)
  return allowedForms
}

function forbidden(): Set<string> {
  if (!forbiddenForms) {
    const set = formsOf(FORBIDDEN_GROUPS)
    for (const term of CONDITION_TERMS) set.delete(canonical(term))
    // المواد السامّة تُضاف **بعد** حذف كلمات الحالات كي لا يُلغيها حذفٌ عرَضي.
    for (const term of TOXIC_TERMS) set.add(canonical(term))
    forbiddenForms = set
  }
  return forbiddenForms
}

/** نافذة العبارات: أطول مفتاح بالكلمات في الجدولين («بنادول كولد اند فلو»). */
const MAX_PHRASE_WORDS = 5

function phrasesIn(tokens: readonly string[]): string[] {
  const out: string[] = []
  for (let i = 0; i < tokens.length; i++) {
    for (let size = Math.min(MAX_PHRASE_WORDS, tokens.length - i); size >= 1; size--) {
      out.push(tokens.slice(i, i + size).join(" "))
    }
  }
  return out
}

export type OtcVerdict = { allowed: boolean; reason: "ok" | "forbidden" | "not_listed" | "prescription" | "injectable" }

/**
 * هل يجوز عرض هذا المنتج في نتيجة عَرَض صحّي؟
 *
 * الترتيب مُلزِم: **النقض قبل الإذن**. صنف يحمل اسمًا ممنوعًا يُرفض ولو حمل معه اسمًا مسموحًا —
 * وهي الحالة الواقعية لا النادرة: «سولبادين» باراسيتامول + كودايين، فالإذن وحده كان يمرّرها.
 */
export function otcVerdict(product: { name?: string | null; requires_prescription?: boolean | null }): OtcVerdict {
  if (product?.requires_prescription === true) return { allowed: false, reason: "prescription" }

  const tokens = searchTokens(typeof product?.name === "string" ? product.name : "")
  if (!tokens.length) return { allowed: false, reason: "not_listed" }

  // الشكل الصيدلاني قبل الاسم: ما يُحقَن يُرفض ولو كان جزيئه في قائمة الإذن.
  const injectable = new Set(INJECTABLE_FORMS.map(canonical))
  for (const token of tokens) {
    if (injectable.has(token)) return { allowed: false, reason: "injectable" }
  }

  const phrases = phrasesIn(tokens)
  const deny = forbidden()
  for (const phrase of phrases) {
    if (deny.has(phrase)) return { allowed: false, reason: "forbidden" }
  }

  const allow = allowed()
  for (const phrase of phrases) {
    if (allow.has(phrase)) return { allowed: true, reason: "ok" }
  }

  return { allowed: false, reason: "not_listed" }
}

/** الصيغة المختصرة للاستعمال في الفلترة. */
export function isOtcEligible(product: { name?: string | null; requires_prescription?: boolean | null }): boolean {
  return otcVerdict(product).allowed
}
