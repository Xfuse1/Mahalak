/**
 * هل فئة هذا المتجر صيدلية؟
 *
 * تعيش هنا لا في مكوّن الواجهة كي **يستعملها السيرفر أوّلًا**: الفحص الذي يعيش في العميل وحده حراسةُ
 * عرضٍ لا حراسةُ إذن — والبائع يستدعي الأكشن مباشرةً بلا واجهة أصلًا.
 *
 * المطابقة على الجذر بعد التطبيع لا على نصّ ثابت: الفئة المخزَّنة على الإنتاج «صيداليات» بهجاء
 * يخالف «صيدليات»، ومقارنة نصّية مباشرة كانت ستحجب صيدلية حقيقية وتفتح البابَ لمن يكتب هجاءً ثالثًا.
 *
 * `normalize` يُحقَن (من `lib/utils/arabic`) كي يبقى هذا الملف نقيًّا يستورده العميل والسيرفر معًا.
 */
export function isPharmacyCategory(category: unknown, normalize: (input: unknown) => string): boolean {
  return /صيدل|صيدال/.test(normalize(typeof category === "string" ? category : ""))
}

/** هل الإقرار المخزَّن صالح للنسخة الحالية؟ نسخة أقدم = موافقة على نصّ آخر ⇒ تُطلب من جديد. */
export function hasValidConsent(consent: unknown): boolean {
  if (!consent || typeof consent !== "object") return false
  const c = consent as Partial<PharmacyConsent>
  return Number(c.version) === PHARMACY_CONSENT_VERSION && typeof c.accepted_at === "string" && !!c.accepted_at
}
